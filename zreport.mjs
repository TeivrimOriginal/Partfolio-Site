// Маркеры работы с ПК в ТЕКСТЕ вакансии. Это отдельная метка, а не
// направление: кладовщик, у которого «работа в 1С», кладовщиком и остаётся,
// но работать с компьютером он будет — и это ровно то, что ищется во второй
// таблице.
const PC_MARKERS = [
  /(?:^|[^а-яёa-z])1с(?:[^а-яёa-z]|$)|1с-предприятие/i,
  /работа (на|в) пк|знание пк|уверенн(ый|ая) пользовател(ь|ем) пк|компьютер/i,
  /принтер|картридж|мфу|оргтехник/i,
  /excel|word|ms office|1с:предприятие|электронн(ая|ые) таблиц/i,
  /ввод данных|оцифровк|сканирован|электронн(ое|ые) (архив|документ)/i,
  /сети|скс|lan\b|ethernet|wi-?fi|маршрутизатор/i,
];
function pcInDesc(v) {
  const t = v.desc || '';
  return PC_MARKERS.filter(re => re.test(t)).length;
}

// --- Что закрывает вакансию для студента СПО без высшего ---
// Оба правила вынесены в отдельные модули с тестами на реальные фразы:
//   zdegree-rule.mjs — требование высшего (три разных смысла слова «высшее»)
//   zexp-rule.mjs     — названный минимум опыта (по предложению, с омоглифами)
// Старый шаблон EXP_BLOCK удалён: он требовал, чтобы перед «от N лет» стояло
// слово «опыт», и потому не видел «Опыт от 3 лет», «не менее 1 года» и
// «2x лет» (последнее — с латинскими буквами). Проверено на 561 вакансии с
// меткой опыта: правило ловило 80, теперь ловит больше 400.

// --- Признаки «совмещается с учёбой» ---
// Разбор часов и метки совмещения живут в zhours.mjs: там же тест на
// реальных строках поля «Рабочие часы» из выборки hh.
function studyFit(v) {
  const marks = studyMarks(v);
  const h = parseHours(v.hours);
  return { r: marks, max: h.max, min: h.min };
}

// Направление определяется ТОЛЬКО по заголовку.
//
// Почему: при поиске по описанию кладовщик с «работой в 1С» уезжал в
// направление «1С», а «Инженер ПТО (электросетевая компания)» — в «сети».
// Проверено: 70 вакансий из 1241 содержат «1С» только в описании, и все они
// не про 1С. Работа с ПК в описании — это отдельная метка, см. PC_MARKERS.
function pickDir(v) {
  const t = v.title || '';
  for (const d of DIRECTIONS) {
    if (d.key === 'other') continue;
    if (d.re.test(t)) return d;
  }
  return DIRECTIONS[DIRECTIONS.length - 1];
}

