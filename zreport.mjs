function locality(v) {
  const c = v.city || '';
  const title = v.title || '';
  if (FAR_CITIES.test(c) || FAR_CITIES.test(title)) return 2;   // далеко/вахта
  if (LOCAL_CITIES.test(c) || LOCAL_CITIES.test(title)) return 0; // рядом с домом
  return 1;  // Свердловская область, но не соседний город
}

