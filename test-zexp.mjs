// Тест правила «нужен опыт». Все фразы — из реальных вакансий выборки.
import { expCheck } from './zexp-rule.mjs';

const MUST_BLOCK = [
  ['Опыт управления коллективом от 3 лет (руководство отделом, магазином, производством)', 'опыт от 3 лет'],
  ['опыт работы в аналогичной отрасли на инженерно-технических должностях - прораб, мастер от 3х лет', '3х лет'],
  ['Тpебовaния: oпыт paбoты в электpoмонтаже oт 2x лeт', '2x лет'],
  ['Требования: опыт от 1 года, документы по разряду.', 'от 1 года'],
  ['Опыт работы на промышленных объектах от 2 лет.', 'от 2 лет'],
  ['Имеешь опыт работы в розничной торговле от 6 месяцев', 'от 6 месяцев'],
  ['Есть опыт прямых розничных продаж не менее 1 года', 'не менее 1 года'],
  ['Опыт от 3 лет, подтверждённые удостоверения и допуск к высотным работам.', 'Опыт от 3 лет'],
  ['Опыт работы в 1С не менее 1 года', 'не менее 1 года'],
  ['Требуется опыт работы от 2 лет в аналогичной должности', 'от 2 лет'],
  ['Опыт работы в продажах 2+ года', '2+ года'],
];

const MUST_PASS = [
  ['Без опыта работы приветствуется', 'без опыта'],
  ['Опыт работы не важен, всему научим', 'не важен'],
  ['Желателен опыт работы в 1С, но не обязателен', 'желателен'],
  ['Опыт работы от 3 лет приветствуется, но не обязателен', 'не обязателен'],
  ['Возможность получения опыта работы в компании', 'возможность получения'],
  ['Опыт работы в профессии приветствуется', 'приветствуется'],
  ['Работа с 1С: возможно обучение на месте', 'возможно обучение'],
  ['Без опыта работы, обучение за счёт предприятия', 'без опыта'],
];

let fail = 0;
for (const [text, why] of MUST_BLOCK) {
  const r = expCheck(text);
  if (!r.hard.length) { console.log('FAIL должен блокировать:', why, '::', text.slice(0, 70)); fail++; }
}
for (const [text, why] of MUST_PASS) {
  const r = expCheck(text);
  if (r.hard.length) { console.log('FAIL НЕ должен блокировать:', r.hard.join(', '), '::', text.slice(0, 70)); fail++; }
}

// Порог: «от 6 месяцев» блокирует, «от 3 месяцев» — нет
if (!expCheck('Имеешь опыт работы в розничной торговле от 6 месяцев').hard.length) { console.log('FAIL: 6 месяцев должно блокировать'); fail++; }
if (expCheck('Опыт работы от 3 месяцев приветствуется').hard.length) { console.log('FAIL: 3 месяцев не должно блокировать'); fail++; }

// «Опыт работы не важен» — не блокирует (слово «опыт» есть, числа нет)
if (expCheck('Опыт работы не важен').hard.length) { console.log('FAIL: «не важен» не должно блокировать'); fail++; }

console.log(fail ? `ПРОВАЛЕНО: ${fail}` : `правило «опыт» проверено: ${MUST_BLOCK.length} блокирующих + ${MUST_PASS.length} пропускаемых + 3 пороговых`);
process.exit(fail ? 1 : 0);
