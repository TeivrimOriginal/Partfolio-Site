// Правило «требуется высшее образование» — по контексту предложения.
//
// ПОЧЕМУ ИМЕННО ПРЕДЛОЖЕНИЕ, а не слова вокруг: каждая из трёх версий
// правила ломалась на реальных фразах из выборки.
//
//   версия 1 (замены): «высшее или среднее» вырезалось и заменялось меткой
//     «ВЫСШЕЕ_ИЛИ_СРЕДНЕЕ» — но жёсткое правило «высшее + следующее слово»
//     срабатывало на метку, и «высшее или среднее ТЕХНИЧЕСКОЕ образование»
//     блокировалось, хотя СПО там подходит.
//
//   версия 2 (контекст ±80 символов): окно обрывалось раньше, чем
//     «за счёт предприятия», поэтому льгота не распознавалась; и слова
//     «среднее» и «высшее» в одной фразе определялись независимо.
//
//   версия 3 (эта): берём ПРЕДЛОЖЕНИЕ целиком и смотрим на всё, что в нём
//     есть. «высшее или среднее» и «средне-специальное или высшее» —
//     в одном предложении, значит СПО подходит. «возможность получения
//     ... образования за счёт предприятия» — тоже предложение, целиком.
//
// ТРИ СМЫСЛА СЛОВА «ВЫСШЕЕ», и только один закрывает вакансию:
//   1) ТРЕБОВАНИЕ — «Высшее образование по направлению ...»     → блокирует
//   2) АЛЬТЕРНАТИВА — «высшее или среднее профессиональное»    → СПО подходит
//   3) ЛЬГОТА — «возможность получения ... образования за счёт
//      предприятия» — предприятие САМО ОПЛАЧИВАЕТ учёбу. Для джуна без
//      высшего это лучший вариант из возможных.
//
// Границы слов заданы руками: в JavaScript `\w` и `\b` не работают с
// кириллицей (это уже было записано в NOTES и повторилось здесь).

const W = '[а-яёa-z0-9]';
const RE_VYSSHEE = new RegExp(`высш${W}*`, 'gi');
const RE_SRED = new RegExp(`средн${W}*`, 'gi');
const RE_SRED_PROF = new RegExp(`средн${W}*\\s*[- ]?\\s*(?:профессиональн|специальн|техническ)`, 'gi');
// «наличие высшего образования» — требование, даже если в скобках «желательно»:
// скобка относится к СПЕЦИАЛИЗАЦИИ («желательно педагогического»), а не к самому
// высшему. Проверено на реальной вакансии «Педагог-организатор».
const RE_NALICHIE = new RegExp(`наличи${W}*\\s+высш`, 'i');

// Разбивка на предложения: точка/точка с запятой/перенос строки, но не сокращения
function sentences(text) {
  return String(text || '')
    .split(/(?<=[.!?;])\s+|\n+/i)
    .map(s => s.trim())
    .filter(Boolean);
}

// Предложение, содержащее данное совпадение
function sentenceOf(text, index) {
  const sents = sentences(text);
  let pos = 0;
  for (const s of sents) {
    const at = text.indexOf(s, pos);
    if (at === -1) { pos += s.length; continue; }
    if (index >= at && index < at + s.length) return s;
    pos = at + s.length;
  }
  return '';
}

export function degreeCheck(desc) {
  const d = String(desc || '');
  const hard = [];
  const soft = new Set();

  // --- Отдельные случаи, которые не про «высшее» ---
  if (/магистрат/i.test(d)) hard.push('требуется магистратура');
  if (new RegExp(`диплом${W}*\\s+(?:о\\s+)?высшем`, 'i').test(d)) hard.push('требуется диплом о высшем');
  if (new RegExp(`незаконч(?:енн|енное|енный)\\s+высш`, 'i').test(d)) hard.push('требуется незаконченное высшее');
  if (new RegExp(`образован${W}*\\s+высш(?:ее|его)`, 'i').test(d)) {
    // «образование высшее инженерное»
    const m = d.match(new RegExp(`.{0,40}образован${W}*\\s+высш(?:ее|его)[^.]{0,60}`, 'i'));
    const frag = m ? m[0] : '';
    if (!/желательн/i.test(frag)) {
      if (/профильно|техническ|медицинск|педагогическ|юридическ|экономическ|инженерн|технологическ|военн/i.test(frag))
        hard.push('требуется высшее профильное');
      else hard.push('требуется высшее образование');
    }
  }

  // --- Каждое вхождение «высш…» разбирается по предложению ---
  RE_VYSSHEE.lastIndex = 0;
  let m;
  const seenHard = new Set();
  while ((m = RE_VYSSHEE.exec(d)) !== null) {
    const sent = sentenceOf(d, m.index);
    if (!sent) continue;

    // 1) ЛЬГОТА: предприятие само даёт образование.
    if (/возможност|выда[её]т|предостав|оплачива|организуем|оплатим/i.test(sent) &&
      /образован|диплом|учеб/i.test(sent) &&
      (/за\s+счет|за\s+счёт|в\s+процессе\s+работы|продолж|бесплатно|на\s+предприяти|на\s+предприятии|компани/i.test(sent) ||
        /получи\w*\s+(средн|высш)|получени\w*\s+(средн|высш)/i.test(sent))) {
      soft.add('предприятие даёт образование');
      continue;
    }

    // 2) АЛЬТЕРНАТИВА: в этом же предложении есть «среднее/средне-специальное».
    //    Значит СПО подходит, даже если стоит вторым в списке.
    RE_SRED.lastIndex = 0; RE_SRED_PROF.lastIndex = 0;
    const hasSred = RE_SRED.test(sent);
    const hasSredProf = RE_SRED_PROF.test(sent);
    RE_SRED.lastIndex = 0; RE_SRED_PROF.lastIndex = 0;
    if (hasSred) {
      // Если «среднее» и «высшее» — альтернативы, разделённые «или»/«;»,
      // то СПО подходит. Если «среднее» просто упоминается отдельно
      // (например «высшее образование; средне-специальное образование» —
      // это тоже перечисление вариантов), СПО тоже подходит.
      soft.add('СПО подходит');
      continue;
    }
    if (hasSredProf) { soft.add('СПО подходит'); continue; }

    // 3) ПОЖЕЛАНИЕ, а не условие.
    //    «Наличие высшего образования (желательно, педагогического)» — скобка
    //    относится к специализации, а само высшее остаётся требованием.
    if (!RE_NALICHIE.test(sent) &&
      (/желательн|преимуществ|будет\s+плюс|приветству|хотел[ьи]|будет\s+хорошим\s+бонусом/i.test(sent))) {
      soft.add('высшее — плюс, а не условие');
      continue;
    }

    // 4) Настоящее требование.
    const after = d.slice(m.index + m[0].length, m.index + m[0].length + 45);
    if (/образован|диплом/i.test(after)) {
      let why = 'требуется высшее образование';
      if (/профильно|техническ|медицинск|педагогическ|юридическ|экономическ|инженерн|технологическ|военн/i.test(after))
        why = 'требуется высшее профильное';
      if (!seenHard.has(why)) { seenHard.add(why); hard.push(why); }
    }
  }

  return { hard: [...new Set(hard)], soft: [...soft] };
}
