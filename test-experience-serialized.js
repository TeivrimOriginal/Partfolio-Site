let bad = 0;

// 1. Сериализованная копия собирается и возвращает нужные функции.
let page;
try {
  page = new Function(pageRuleSource())();
} catch (e) {
  console.log('  СЕРИАЛИЗАЦИЯ НЕ СОБРАЛАСЬ: ' + (e && e.message));
  process.exit(1);
}
for (const fn of ['reasonIn', 'monthsFloor', 'tooExperienced']) {
  if (typeof page[fn] !== 'function') {
    console.log('  в сериализованной копии нет функции ' + fn);
    bad++;
  }
}

// 2. Порог в обеих копиях один.
if (page.MONTH_THRESHOLD !== MONTH_THRESHOLD) {
  console.log('  порог разошёлся: node ' + MONTH_THRESHOLD + ', страница ' + page.MONTH_THRESHOLD);
  bad++;
}

// 3. Вердикты совпадают на всём корпусе.
for (const t of CORPUS) {
  const a = reasonIn(t);
  const b = page.reasonIn(t);
  const na = a ? a.rule + '|' + a.matched : 'нет';
  const nb = b ? b.rule + '|' + b.matched : 'нет';
  if (na !== nb) {
    console.log('  РАСХОЖДЕНИЕ на «' + String(t).slice(0, 46) + '»: node ' + na + ', страница ' + nb);
    bad++;
  }
  const fa = monthsFloor(t);
  const fb = page.monthsFloor(t);
  if (fa !== fb) {
    console.log('  РАСХОЖДЕНИЕ порога на «' + String(t).slice(0, 46) + '»: node ' + fa + ', страница ' + fb);
    bad++;
  }
}

// 4. В сериализованной копии не должно остаться побегов от CommonJS,
//    иначе она когда-нибудь упадёт в странице.
const src = pageRuleSource();
if (/module\.exports/.test(src)) {
  console.log('  в строке для страницы остался module.exports');
  bad++;
}
if (/\brequire\s*\(/.test(src)) {
  console.log('  в строке для страницы остался require');
  bad++;
}

console.log('фраз в корпусе: ' + CORPUS.length + ', расхождений node и страницы: ' + bad);
process.exit(bad === 0 ? 0 : 1);