// Проверка дат и формулировок в резюме.
//
// Что ловит. В одиннадцати резюме стояло «с 2022», хотя ничем это не
// подтверждается: самый ранний публичный репозиторий — 2024-10-26, первый
// Python — 2026-09-29, первый Rust — 2026-09-20, Kwork публичную дату не
// отдаёт. В письмах год вычистили как недоказуемый, а в резюме — нет, и
// резюме прикрепляется к отклику. Такое расхождение хуже, чем просто ошибка:
// письмо говорит одно, прикреплённый файл — другое.
//
// Почему именно такие проверки. Каждый пункт здесь — реальная ошибка,
// найденная в этом репозитории, а не абстрактное правило:
//
//   1. Год начала работы в резюме            ← «с 2022», снимает hh и дату
//   2. Слово «коммерческий» в резюме         ← противоречит пустому блоку
//                                               опыта на hh и письмам
//   3. «2024» рядом с Rust                   ← первый репозиторий 2026-09-20
//   4. Ссылки на kwork.ru/user/teivrim        ← единственное доказательство
//                                               факта, без него строка о
//                                               заказах ничего не доказывает
//   5. Запрещённые формулировки из требований
//
// Проверка офлайн, сеть не нужна. Даты сверяются с evidence-срезом
// save-evidence.js, а не с живым GitHub: иначе тест падал бы при каждом
// новом репозитории.
const fs = require('fs');
const path = require('path');

const RESUMES = fs
  .readdirSync(__dirname)
  .filter((f) => /^resume.*\.html$/i.test(f))
  .sort();

let bad = 0;

// Что hh и письма запрещают дословно. Формулировки из требований пользователя.
const FORBIDDEN = [
  'удалённая работа полностью',
  'готов к стендаму',
  'стажёрская ставка',
  'стажерская ставка',
  'самозанятость',
];

// Единственный подтверждаемый год начала: первый публичный репозиторий.
// Измерено hh-start-date.js: just-MESSENGER-php, 2024-10-26. Раньше — нет.
const EARLIEST_PUBLIC = '2024-10-26';

function plainOf(file) {
  return fs
    .readFileSync(path.join(__dirname, file), 'utf8')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&middot;|&mdash;|&laquo;|&raquo;|&nbsp;/g, ' ')
    .replace(/\s+/g, ' ');
}

console.log('резюме: ' + RESUMES.length + ', сверка с самым ранним публичным репозиторием ' + EARLIEST_PUBLIC);
console.log('');

for (const file of RESUMES) {
  const text = plainOf(file);

  // 1. Год начала работы. Любой год раньше первого публичного репозитория
  //    не подтверждается. Проверяем все годы, а не только 2022: подставить
  //    вместо него другой непроверяемый год — то же самое враньё.
  const years = [...new Set((text.match(/\b(20\d\d)\b/g) || []).map(Number))].sort();
  for (const y of years) {
    if (y === 2026) continue; // текущий год, проекты и CI правятся сейчас
    const iso = y + '-01-01';
    if (iso < EARLIEST_PUBLIC) {
      console.log('  ' + file + ': год ' + y + ' раньше первого публичного репозитория ' + EARLIEST_PUBLIC);
      const m = text.match(new RegExp('.{0,60}\\b' + y + '\\b.{0,60}'));
      if (m) console.log('      « ' + m[0].trim() + ' »');
      bad++;
    }
  }

  // 2. «Коммерческий» в резюме. Блок опыта на hh остаётся пустым, письма это
  //    признают, а в резюме слово стоит — рекрутер видит противоречие.
  if (/коммерческ/i.test(text)) {
    const m = text.match(/.{0,60}коммерческ\w*.{0,60}/i);
    console.log('  ' + file + ': слово «коммерческий» — « ' + (m ? m[0].trim() : '') + ' »');
    bad++;
  }

  // 3. Rust и 2024. Первый публичный репозиторий на Rust — 2026-09-20,
  //    поэтому «Rust с 2024» не подтверждается ничем.
  const rustYear = text.match(/Rust[^.]{0,30}\b(20\d\d)\b|\b(20\d\d)\b[^.]{0,30}Rust/i);
  if (rustYear && (rustYear[1] === '2024' || rustYear[2] === '2024')) {
    console.log('  ' + file + ': Rust с 2024 — первый репозиторий на Rust 2026-09-20');
    bad++;
  }

  // 4. Строка про заказы на Kwork обязана содержать ссылку на профиль.
  //    Иначе утверждение «брал заказы» нечем подтвердить — это ровно тот
  //    случай, который в NOTES назван недоказуемым.
  //
  //    Проверка только для файлов с блоком опыта. resumes.html — оглавление,
  //    там «Заказы на Kwork» стоит в описании карточки, а сама карточка
  //    ведёт на resume-python.html, где ссылка на профиль есть. Требовать
  //    ссылку от оглавления бессмысленно: он никого ни в чём не убеждает.
  const raw = fs.readFileSync(path.join(__dirname, file), 'utf8');
  const hasExperienceBlock = /Опыт работы|Work Experience/.test(text);
  if (hasExperienceBlock && /Kwork/.test(text) && !/kwork\.ru\/user\/teivrim/.test(raw)) {
    console.log('  ' + file + ': есть блок опыта с Kwork, но нет ссылки kwork.ru/user/teivrim — факт нечем подтвердить');
    bad++;
  }

  // 5. Запрещённые формулировки.
  for (const f of FORBIDDEN) {
    if (text.toLowerCase().includes(f.toLowerCase())) {
      console.log('  ' + file + ': запрещённая формулировка «' + f + '»');
      bad++;
    }
  }
}

console.log('');
if (bad === 0) {
  console.log('нарушений: 0 — даты и формулировки в резюме соответствуют тому, что можно подтвердить');
  process.exit(0);
}
console.log('НАРУШЕНИЙ: ' + bad);
process.exit(1);