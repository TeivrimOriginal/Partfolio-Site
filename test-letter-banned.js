// Проверяет, что в письмах нет формулировок, которые ТЗ запрещает.
//
// Зачем это отдельный тест, а не обещание в комментарии. ТЗ запрещает в письмах
// и резюме: «удалённая работа полностью», «готов к стендаму», «стажёрская
// ставка», «самозанятость», а также недоказуемый 2022 год и слово
// «коммерческий» применительно к опыту, который нельзя подтвердить. Каждое
// из этих слов уже ПОЯВЛЯЛОСЬ в письмах раньше, поэтому наличие в коде
// ничего не гарантирует — гарантирует проверка.
//
// Что проверяется на живых данных: берутся письма из базы. Если база пуста,
// тест это говорит и ПРОХОДИТ — пустой набор не доказывает ничего, но и не
// должен падать из-за того, что сборщик ещё не запускался. Наполнение
// проверяется отдельно: тест ругается, если в базе нет ни одного письма.
//
// Отдельно проверяется длина: composeLetter бросает исключение, если письмо
// длиннее предела, но предел известен только ему. Здесь — верхняя граница,
// выше которой письмо на hh обрежут при вставке.

const { open, DB_FILE } = require('./hsw-db.js');

// Каждый запрет — с причиной. Причина в отчёте, а не только факт совпадения:
// иначе непонятно, что чинить.
const BANNED = [
  {
    re: /готов\s+к\s+стендаму/i,
    why: 'ТЗ: обещание бесплатной стажировки звучит как согласие работать без оплаты',
  },
  {
    re: /стаж[ёе]рская\s+ставка/i,
    why: 'ТЗ: прямо запрещено',
  },
  {
    re: /стажировк[аи]\s+бесплатн/i,
    why: 'то же самое другими словами',
  },
  {
    re: /удалённая\s+работа\s+полностью/i,
    why: 'ТЗ: прямо запрещено',
  },
  {
    re: /работа[еа]?\s+полностью\s+удалённ/i,
    why: 'то же самое в обратном порядке слов',
  },
  {
    re: /\bсамозанят/i,
    why: 'ТЗ: прямо запрещено',
  },
  {
    re: /\b2022\b/g,
    why: 'ТЗ: год недоказуем — в резюме и письмах его быть не должно',
  },
  {
    re: /коммерческ\w*\s+(опыт|проект|разработка|работа)/i,
    why: 'ТЗ: слово «коммерческий» нечестно, если опыт не подтверждается документами',
  },
];

// Границы длины. composeLetter ограничивает письмо само и падает при превышении,
// но в базе может оказаться письмо, написанное ранее. hh обрезает текст
// примерно после 5000 знаков в поле отклика — всё, что дальше, не доходит.
const LEN_OK = 5000;
const LEN_WARN = 3000;

const db = open(DB_FILE);

try {
  const letters = db
    .prepare('SELECT l.id, l.subject, l.body, l.fit, l.state, v.site_id, v.title FROM letters l JOIN vacancies v ON v.id = l.vacancy_id ORDER BY l.id')
    .all();

  console.log('=== запрещённые формулировки в письмах ===');
  console.log('  писем в базе: ' + letters.length);
  if (letters.length === 0) {
    console.log('  ПИСЕМ НЕТ — проверка ничего не утверждает. Запустите hsw-letters.js.');
    console.log('  Это не ошибка теста, но и не доказательство чистоты.');
  }

  let failures = 0;
  const hits = [];

  for (const l of letters) {
    const where = [];
    if (l.subject) where.push(['subject', String(l.subject)]);
    where.push(['body', String(l.body || '')]);

    for (const [field, text] of where) {
      for (const rule of BANNED) {
        // Правило на год 2022 имеет флаг g, поэтому lastIndex надо обнулять:
        // без этого вторая проверка того же текста начнётся с конца прошлого
        // совпадения и даст ложный ноль. Это тот же класс, что с while(exec)
        // без g, только наоборот — тихо недосчитать.
        const re = new RegExp(rule.re.source, rule.re.flags);
        let m;
        let found = 0;
        while ((m = re.exec(text)) !== null) {
          found++;
          if (found >= 3) break;
          const at = Math.max(0, m.index - 40);
          hits.push({
            id: l.site_id, field, rule, snippet: text.slice(at, m.index + 60).replace(/\s+/g, ' '),
          });
          if (!re.global) break;
        }
      }
    }
  }

  if (hits.length === 0) {
    console.log('  запрещённых формулировок не найдено');
  } else {
    failures += hits.length;
    for (const h of hits) {
      console.log('  ПРОВАЛ ' + h.id + ' (' + h.field + '): ' + h.rule.why);
      console.log('      правило: ' + h.rule.re);
      console.log('      текст: …' + h.snippet + '…');
    }
  }

  console.log('\n=== длина писем ===');
  for (const l of letters) {
    const n = String(l.body || '').length;
    if (n > LEN_OK) {
      console.log('  ПРОВАЛ ' + l.site_id + ': ' + n + ' символов, предел ' + LEN_OK + ' — письмо обрежут при вставке');
      failures++;
    } else if (n > LEN_WARN) {
      console.log('  ВНИМАНИЕ ' + l.site_id + ': ' + n + ' символов (порог ' + LEN_WARN + ')');
    }
  }
  if (letters.length) console.log('  самая длинная: ' + Math.max(...letters.map((l) => String(l.body || '').length)) + ' символов');

  // Ноль писем — не повод считать проверку выполненной. Отмечаем явно.
  console.log('\n=== итог ===');
  if (letters.length === 0) {
    console.log('  писем нет: ни провалов, ни доказательства. Наполните базу и прогоните снова.');
    process.exitCode = 1;
  } else if (failures === 0) {
    console.log('  провалов: 0 на ' + letters.length + ' письмах');
  } else {
    console.log('  провалов: ' + failures);
    process.exitCode = 1;
  }
} finally {
  db.close();
}