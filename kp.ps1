<#
  kp.ps1 — генератор коммерческого предложения (этап B2) и счёта (B4).

  Смысл: цену нельзя называть «на глаз», иначе либо продешевить, либо клиент
  уйдёт. Смета собирается из объёма, а не выдумывается. Все блоки, которые
  клиент не выбрал, попадают в «не входит» — это защищает от бесконечных
  «а ещё добавьте вот это за бесплатно».

  Run:
    powershell -ExecutionPolicy Bypass -File kp.ps1 -Id d001 -Pages 6 -Form WhatsApp -Map -Catalog
    powershell -ExecutionPolicy Bypass -File kp.ps1 -Id d001 -Concept   # быстрый концепт
#>
[CmdletBinding()]
param(
  [string]$Id = '',
  [string]$DealsFile = 'deals.csv',
  [int]$Pages = 5,
  [switch]$Map,
  [switch]$Catalog,
  [switch]$Multipage,
  [string]$Form = 'заявка на e-mail',
  [switch]$Concept,
  [int]$Discount = 0
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$db = if ([IO.Path]::IsPathRooted($DealsFile)) { $DealsFile } else { Join-Path $root $DealsFile }
if (-not (Test-Path $db)) { throw "нет доски сделок: $db. Сначала pipeline.ps1 init && add" }

$rows = @(Import-Csv $db)
$deal = $null
if ($Id) { $deal = $rows | Where-Object { $_.id -eq $Id } | Select-Object -First 1 }
else { $deal = $rows | Where-Object { $_.stage -eq 'b1' -or $_.stage -eq 'b2' } | Select-Object -First 1 }
if (-not $deal) { throw "не нашёл сделку $Id" }

# ---- прайс: считается от объёма, а не выдумывается ----
$base = 25000
$work = @()
$work += [pscustomobject]@{ item = "Главная страница: блок услуг, блок «о нас», форма заявки"; add = 0 }
$work += [pscustomobject]@{ item = "Адаптивная вёрстка (телефон + планшет + десктоп)"; add = 0 }
$work += [pscustomobject]@{ item = "Домен и хостинг на ваше имя, настройка почты"; add = 0 }
$work += [pscustomobject]@{ item = "Форма заявки: $Form"; add = if ($Form -match 'WhatsApp|Telegram') { 3000 } else { 0 } }
if ($Map) { $work += [pscustomobject]@{ item = 'Карта с меткой на адрес'; add = 2000 } }
if ($Multipage) { $work += [pscustomobject]@{ item = 'Полноценное меню и 2-3 внутренние страницы'; add = 8000 } }
if ($Catalog) { $work += [pscustomobject]@{ item = 'Каталог товаров/услуг с фильтрами'; add = 15000 } }
$extra = $Pages - 5
if ($extra -gt 0) { $work += [pscustomobject]@{ item = "Дополнительные страницы ($extra шт.)"; add = ($extra * 2500) } }

$sum = $base + (($work | Measure-Object -Property add -Sum).Sum)
$prepay = [Math]::Round(($sum * 0.5) / 500) * 500
$rest = $sum - $prepay
if ($Discount -gt 0) { $prepay = [Math]::Round(($sum - $Discount) / 2 / 500) * 500; $rest = ($sum - $Discount) - $prepay }

$notIncluded = @('фотографии и тексты (заказчик предоставляет или отдельно 500 ₽/фото)',
  'продвижение и реклама (SEO, контекст) — отдельный проект',
  'наполнение и обновление товаров после сдачи',
  'доработки сверх согласованной сметы — 1 500 ₽/час, только по письменному согласованию')

$lines = @()
foreach ($w in $work) { $lines += ('  {0,-62} {1,8} ₽' -f $w.item, $(if ($w.add -gt 0) { $w.add } else { 0 })) }

$kp = @"
КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ
для {0} · ИНН {1} · {2}

Профиль деятельности (из открытого реестра): {3}
Дата: {4}

────────────────────────────────────────────────────────────────
ЧТО ДЕЛАЕМ
────────────────────────────────────────────────────────────────
{5}

  ИТОГО                                       {6} ₽

────────────────────────────────────────────────────────────────
КАК ПЛАТИМ
────────────────────────────────────────────────────────────────
  1) 50% предоплата до начала работы            {7} ₽
  2) 50% после приёмки и перевода домена       {8} ₽

  Банковские реквизиты / ссылку на оплату картой пришлю отдельно.
  Работаю как ИП, чек самозанятого предоставляю.

────────────────────────────────────────────────────────────────
СРОКИ
────────────────────────────────────────────────────────────────
  Договор и предоплата   →  старт работ
  Макеты на согласование →  2 дня после предоплаты
  Сборка                 →  5-7 рабочих дней
  Передача               →  домен на ваше имя, доступы ваши, видеоинструкция

────────────────────────────────────────────────────────────────
ГАРАНТИИ
────────────────────────────────────────────────────────────────
  14 дней на правки по содержанию (тексты, фото, контакты)
  30 дней на работоспособность форм и домена
  Исходники и файлы проекта передаю вам

────────────────────────────────────────────────────────────────
НЕ ВХОДИТ В СТОИМОСТЬ
────────────────────────────────────────────────────────────────
{9}

────────────────────────────────────────────────────────────────
ЧТО НУЖНО ОТ ВАС
────────────────────────────────────────────────────────────────
  1. Логотип или текст названия (если нет — сделаю текстовый)
  2. 3-5 фото вашей работы или услуги
  3. Список услуг/товаров с ценами, если нужен каталог
  4. Контакты, которые должны быть на сайте

────────────────────────────────────────────────────────────────
Следующий шаг: ответьте «да» — пришлю договор и счёт на {7} ₽.
Вопросы: {10}
────────────────────────────────────────────────────────────────
"@ -f $deal.company, $deal.inn, $deal.city, $deal.okved,
  (Get-Date -Format 'dd.MM.yyyy'),
  ($lines -join "`r`n"), ('{0:N0}' -f $sum), ('{0:N0}' -f $prepay), ('{0:N0}' -f $rest),
  (($notIncluded | ForEach-Object { '  - ' + $_ }) -join "`r`n"),
  ($deal.email + $(if ($deal.phone) { ' / ' + $deal.phone } else { '' }))

if ($Concept) {
  $kp = @"
БЫСТРО: что именно войдёт в главную страницу
для {0} · {1}

Не макет, а структура — согласуем за 10 минут, прежде чем рисовать.

  1. Шапка: название, чем занимаетесь, телефон, кнопка «написать в WhatsApp»
  2. Первый экран: что вы делаете + 2 цифры или факта (срок, гарантия, объём)
  3. Блок услуг: 4-6 позиций с коротким описанием и ценой «от»
  4. Как мы работаем: 3 шага — заявка → выезд → результат
  5. Фото ваших работ (3-6 штук)
  6. Отзывы или гарантии (если есть)
  7. Форма заявки: имя, телефон, что нужно
  8. Карта и режим работы
  9. Футер с контактами и ссылками на соцсети

Итого {2} страниц, mobile-first, грузится быстро на 3G.
Полный макет и сайт — после договора и 50% предоплаты ({3} ₽).

Согласны с такой структурой — отвечайте «да», пришлю договор.
Не согласны — скажите, что убрать или добавить, поправлю за один день.
"@ -f $deal.company, $deal.city, ('{0:N0}' -f $sum), ('{0:N0}' -f $prepay)
}

$slug = ($deal.company -replace '[^\wа-яА-ЯёЁ\- ]', '' -replace '\s+', '_')
if ($slug.Length -gt 40) { $slug = $slug.Substring(0, 40) }
$outDir = Join-Path $root 'kp'
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
$name = '{0}-{1}.txt' -f $deal.id, $(if ($Concept) { 'концепт' } else { 'смета' })
$outFile = Join-Path $outDir $name
[IO.File]::WriteAllText($outFile, $kp, (New-Object Text.UTF8Encoding $true))

Write-Host ("{0}  {1}" -f $deal.id, $deal.company)
Write-Host ("  объём: {0} стр., форма: {1}{2}{3}" -f $Pages, $Form, $(if ($Map) { ', карта' } else { '' }), $(if ($Catalog) { ', каталог' } else { '' }))
Write-Host ("  сумма: {0} ₽   предоплата: {1} ₽   остаток: {2} ₽" -f $sum, $prepay, $rest)
Write-Host ("  файл: kp\{0}" -f $name)
if ($Concept) { Write-Host '  это концепт: показывается ДО договора. Смета — только после.' }
