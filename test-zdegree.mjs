// Тест правила «требуется высшее». Все фразы взяты из реальных вакансий
// выборки (Заречный + соседи), а не придуманы.
import { degreeCheck } from './zdegree-rule.mjs';

const MUST_BLOCK = [
  ['Высшее образование по направлению «Техносферная безопасность»', 'требуется высшее образование'],
  ['Требования: • Высшее образование; средне-специальное образование;', 'высшее'],
  ['Наличие высшего образования (желательно, педагогического)', 'наличие высшего'],
  ['Требования Высшее техническое образование: машиностроение, строительство', 'высшее'],
  ['Наши ожидания от кандидата: Высшее техническое/ экономическое образование;', 'высшее'],
  ['-образование высшее инженерное;', 'образование высшее'],
  ['Требования: незаконченное высшее образование', 'незаконченное высшее'],
  ['Наличие диплома о высшем образовании', 'диплом'],
  ['Требуется магистратура или специалитет', 'магистратура'],
  ['Требуется высшее профильное образование', 'высшее профильное'],
];

const MUST_PASS = [
  ['Возможность получения средне-специального/высшего образования за счет предприятия; Программа адаптации и наставничество', 'льгота'],
  ['Возможность получения среднего или высшего образования и карьерного роста до офицера', 'льгота'],
  ['Требования : высшее или среднее специальное образование в области строительства', 'или среднее'],
  ['Высшее или среднее профессиональное образование (управленческое, экономическое, техническое)', 'или среднее'],
  ['Требования к кандидату: высшее или среднее техническое образование', 'или среднее'],
  ['Требования: законченное средне-специальное или высшее образование', 'или среднее'],
  ['Требования: высшее или среднетехническое образование по сварочному производству', 'или среднее'],
  ['Возможно трудоустройство Начинающих специалистов с средним и высшим профессиональным образованием', 'средним и высшим'],
];

let fail = 0;
for (const [text, why] of MUST_BLOCK) {
  const r = degreeCheck(text);
  if (!r.hard.length) { console.log('FAIL должен блокировать:', why, '::', text.slice(0, 70)); fail++; }
}
for (const [text, why] of MUST_PASS) {
  const r = degreeCheck(text);
  if (r.hard.length) { console.log('FAIL НЕ должен блокировать:', r.hard.join(','), '::', text.slice(0, 70)); fail++; }
}
// «высшее — плюс» помечается, но не блокирует.
// Проверяем на формулировке, где «желательно» относится к самому высшему,
// а не к специализации.
const soft = degreeCheck('Высшее образование приветствуется, но не обязательно');
if (soft.hard.length) { console.log('FAIL: «не обязательно» должно быть мягким, а не жёстким'); fail++; }
if (!soft.soft.length) { console.log('FAIL: «не обязательно» должно давать мягкую метку'); fail++; }
// Льгота должна давать мягкую метку
const ben = degreeCheck('Возможность получения средне-специального/высшего образования за счет предприятия');
if (ben.hard.length) { console.log('FAIL: льгота не должна блокировать'); fail++; }
if (!ben.soft.some(s => s.includes('предприятие даёт'))) { console.log('FAIL: льгота должна помечаться, получено', JSON.stringify(ben.soft)); fail++; }

console.log(fail ? `ПРОВАЛЕНО: ${fail}` : `правило «высшее» проверено: ${MUST_BLOCK.length} блокирующих + ${MUST_PASS.length} пропускаемых + 4 мягких`);
process.exit(fail ? 1 : 0);
