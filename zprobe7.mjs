// что именно видит правило.
import { degreeCheck } from './zdegree-rule.mjs';

const PHRASES = [
  'Наличие высшего образования (желательно, педагогического)',
  'Возможно трудоустройство Начинающих специалистов с средним и высшим профессиональным образованием.',
  'Возможность получения средне-специального/высшего образования за счет предприятия; Программа адаптации и наставничество',
];

for (const p of PHRASES) {
  console.log('---', p);
  const sents = p.split(/(?<=[.!?;])\s+|\n+/i).map(s => s.trim()).filter(Boolean);
  for (const s of sents) console.log('   предложение:', JSON.stringify(s));
  console.log('   результат:', JSON.stringify(degreeCheck(p)));
}
