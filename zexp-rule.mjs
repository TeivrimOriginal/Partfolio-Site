// Правило «нужен опыт» — по контексту предложения.
//
// Две ошибки, найденные на реальных вакансиях:
//
// 1) ЧИСЛО ЗАПИСАНО ЛАТИНИЦЕЙ. В вакансии «Тpебовaния: oпыт paбoты в
//    электpoмонтаже oт 2x лeт» буква «e» в слове «лет» — латинская. Регулярка
//    с кириллическим «лет» такую вакансию не видела. Работодатели так делают
//    намеренно, чтобы их вакансии не попадали в автоподбор. Поэтому единицы
//    измерения ищутся с допуском латинских омоглифов.
//
// 2) СРОК НАЗВАН, НО НЕ ОБЯЗАТЕЛЕН. «Опыт работы от 3 лет приветствуется,
//    но не обязателен» — это НЕ требование. Первое правило блокировало её.
//
// Ещё: «Опыт управления коллективом от 3 лет» — слово «опыт» есть; «Требования:
// опыт от 1 года» — есть; «Есть опыт прямых розничных продаж не менее 1 года» —
// конструкция «не менее», а не «от». Поэтому шаблон не подходит: нужен разбор
// предложения.
//
// Порог: оплачиваемого опыта работы нет вообще, поэтому любой явно названный
// минимум от 6 месяцев закрывает вакансию.

const W = '[а-яёa-z0-9]';

// Латинские омоглифы кириллицы. В вакансиях их ставят намеренно.
const HOM = { 'е': 'e', 'о': 'o', 'а': 'a', 'с': 'c', 'х': 'x', 'р': 'p', 'у': 'y', 'к': 'k', 'м': 'm', 'т': 't', 'в': 'b', 'н': 'h' };
// Слово с допуском латинских омоглифов: «лет» → л[еe]т
function hom(word) {
  return [...word].map(ch => (HOM[ch] ? `[${ch}${HOM[ch]}]` : ch)).join('');
}

const UNIT_YEAR = `${hom('лет')}|${hom('года')}|${hom('год')}`;
const UNIT_MONTH = `${hom('месяцев')}|${hom('месяца')}|${hom('месяц')}|${hom('мес')}\\.|${hom('мес')}`;

// «3 лет», «3x лет», «2-x лет», «1 год», «6 месяцев», «2+ года»
const RE_PERIOD = new RegExp(
  `(\\d{1,2})\\s*(?:\\+\\s*)?(?:[xхX]|-\\s*[xхX])?\\s*(?:${UNIT_YEAR}|${UNIT_MONTH})`,
  'gi'
);
// «от 3 лет», «не менее 1 года», «как минимум 2 лет»
const RE_MIN = new RegExp(
  `(?:от|не\\s+менее|не\\s+меньше|как\\s+минимум|минимум)\\s*(\\d{1,2})\\s*(?:\\+\\s*)?(?:[xхX])?\\s*(?:${UNIT_YEAR}|${UNIT_MONTH})`,
  'gi'
);
const RE_HALF_YEAR = new RegExp(`пол(?:у|о)года`, 'gi');

// Маркеры опыта, который требуют.
// С допуском латинских омоглифов: в вакансии «Тpебовaния: oпыт paбoты в
// электpoмонтаже oт 2x лeт» слово «опыт» набрано латиницей, и без допуска
// регулярка его не видела — а срок «2x лет» там назван.
const RE_EXP_MARK = new RegExp(
  `${hom('опыт')}${W}*|${hom('стаж')}${W}*|${hom('разработка')}${W}*\\s+на\\s+${hom('коммерческой')}|` +
  `${hom('коммерческий')}${W}*\\s+(?:${hom('опыт')}|${hom('разработка')})|` +
  `${hom('профильно')}${W}*\\s+в\\s+${hom('своей')}|${hom('навык')}${W}*\\s+в\\s+${hom('своей')}|` +
  `${hom('уверенный')}${W}*\\s+${hom('опыт')}`,
  'gi'
);
// Срок назван, но НЕ обязателен.
// «обязателен» и «обязательный» — оба оканчиваются на «обязател», поэтому
// берём корень: первый вариант правила требовал «обязательн» и не видел
// «не обязателен».
const RE_SOFT_REQ = new RegExp(
  `не\\s+${hom('обязател')}|не\\s+${hom('критичен')}|не\\s+${hom('является')}\\s+${hom('обязательным')}|` +
  `${hom('желателен')}|${hom('желательно')}|${hom('приветствуется')}|${hom('приветствуется')}|` +
  `будет\\s+${hom('плюсом')}|не\\s+${hom('важен')}|без\\s+${hom('опыта')}|` +
  `не\\s+${hom('требуется')}|не\\s+${hom('нужен')}|не\\s+${hom('обязательно')}`,
  'gi'
);
// «Стаж» в смысле выслуги лет на одном месте, а не «стажировка».
// «Надбавки за стаж от 1 года» — это надбавка за выслугу, а не требование
// опыта. Проверено на реальных вакансиях Ростелекома, К Телеком, Пятёрочки,
// DNS: таких ложных срабатываний было 20+ из 35 «подозрительных».
const RE_STAJ_VYSLUGE = new RegExp(
  `надбавк${W}*\\s+за\\s+стаж|доплати?${W}*\\s+за\\s+стаж|повышен${W}*\\s+за\\s+стаж|` +
  `${hom('выслуга')}|стаж${W}*\\s+(?:работы|в\\s+компании)|` +
  // «для сотрудников со стажем от 1 года» — выслуга, инструментальный падеж.
  // Тут снова граница слова: `стаж\w*` в JS не ловит кириллическое «ем»,
  // поэтому «стажем от 1 года» проходило мимо правила.
  `со\\s+стаж${W}*\\s+от\\s+\\d|стаж${W}*\\s+от\\s+\\d`,
  'gi'
);
// «с опытом более 3х лет» — это про НАСТАВНИКОВ, а не про кандидата:
// «В нашей команде работают сотрудники с опытом более 3х лет, они настоящие
// профессионалы и подстрахуют на первых порах». Требования к кандидату там нет.
// Сюда же — история компании: «Больше 15 лет мы уверенно идём вперёд благодаря
// инновациям и профессиональному опыту наших сотрудников», «обладает богатым
// опытом в производстве круглого проката».
const RE_ABOUT_OTHERS = new RegExp(
  `${hom('сотрудники')}\\s+с\\s+опытом|${hom('наставники')}\\s+с\\s+опытом|` +
  `${hom('в\\s+нашей\\s+команде')}|${hom('компания')}\\s+работает\\s+\\d+|` +
  `${hom('мы\\s+работаем')}\\s+\\d+|опыт${W}*\\s+наших\\s+сотрудников|` +
  `${hom('богатым')}\\s+опытом|опыт${W}*\\s+в\\s+производстве|стаж${W}*\\s+компании|` +
  `${hom('больше')}\\s+\\d+\\s+лет\\s+мы\\s+${hom('уверенно')}`,
  'gi'
);

function sentences(text) {
  return String(text || '')
    .split(/(?<=[.!?;])\s+|\n+|•/i)
    .map(s => s.trim())
    .filter(Boolean);
}

function periodToMonths(num, unit) {
  const u = unit.toLowerCase();
  if (/мес/.test(u)) return Number(num);
  return Number(num) * 12;
}

export function expCheck(desc) {
  const d = String(desc || '');
  const hard = [];
  const notes = [];
  const sents = sentences(d);
  for (const sent of sents) {
    RE_EXP_MARK.lastIndex = 0;
    const hasMark = RE_EXP_MARK.test(sent);
    RE_EXP_MARK.lastIndex = 0;
    if (!hasMark) continue;

    RE_SOFT_REQ.lastIndex = 0;
    const soft = RE_SOFT_REQ.test(sent);
    RE_SOFT_REQ.lastIndex = 0;
    // «Не обязателен, но приветствуется опыт...» — смягчение стоит в СЛЕДУЮЩЕМ
    // предложении, а срок — в предыдущем. Проверено на реальной вакансии
    // «Повар в кафе на АЗС (ЛУКОЙЛ)»: «...либо опыт работы поваром от 1 года;
    // ... Не обязателен, но приветствуется опыт работы».
    const nearSoft = soft || sents.some((o, i) => {
      if (i === sents.indexOf(sent)) return false;
      const dist = Math.abs(i - sents.indexOf(sent));
      return dist <= 2 && RE_SOFT_REQ.test(o);
    });
    RE_SOFT_REQ.lastIndex = 0;

    // «Надбавки за стаж от 1 года» — это выслуга, а не требование опыта.
    // «сотрудники с опытом более 3х лет» — это про наставников, не про кандидата.
    RE_STAJ_VYSLUGE.lastIndex = 0;
    const vySluga = RE_STAJ_VYSLUGE.test(sent);
    RE_STAJ_VYSLUGE.lastIndex = 0;
    RE_ABOUT_OTHERS.lastIndex = 0;
    const aboutOthers = RE_ABOUT_OTHERS.test(sent);
    RE_ABOUT_OTHERS.lastIndex = 0;
    if (vySluga || aboutOthers) continue;

    const periods = [];
    for (const m of sent.matchAll(RE_PERIOD)) periods.push({ n: m[1], u: m[0] });
    for (const m of sent.matchAll(RE_MIN)) periods.push({ n: m[1], u: m[0] });

    for (const p of periods) {
      const months = periodToMonths(p.n, p.u);
      if (months < 6) continue;
      const shown = p.u.replace(/^\s*(?:от|не\s+менее|не\s+меньше|как\s+минимум|минимум)\s*/i, '').trim();
      if (nearSoft) {
        notes.push(`опыт «${shown}» — но не обязателен`);
      } else {
        hard.push(`нужен опыт: ${shown}`);
      }
    }

    // «полгода» без числа
    RE_HALF_YEAR.lastIndex = 0;
    if (RE_HALF_YEAR.test(sent) && !periods.length) {
      const m = sent.match(new RegExp(`.{0,50}пол(?:у|о)года.{0,40}`, 'i'));
      notes.push('опыт около полугода: ' + (m ? m[0].replace(/\s+/g, ' ') : ''));
    }

    // Требования к знаниям без срока: «опыт работы в 1С»
    if (!periods.length && /в\s+1с|1с\s*:\s*предприятие|в\s+delphi/i.test(sent)) {
      const m = sent.match(new RegExp(`.{0,60}(?:в\\s+1с|1с\\s*:\\s*предприятие|в\\s+delphi).{0,40}`, 'i'));
      const txt = m ? m[0].replace(/\s+/g, ' ') : '';
      if (nearSoft) notes.push('1С — но не обязателен: ' + txt);
      else hard.push('нужен опыт в 1С: ' + txt);
    }
  }
  return { hard: [...new Set(hard)], notes: [...new Set(notes)] };
}
