// Проба регулярок по одной фразе, без экранирования в командной строке.
const W = '[а-яёa-z0-9]';
const OR_MEDIUM = [
  new RegExp(`высш${W}*\\s+или\\s+средн${W}+`, 'gi'),
  new RegExp(`средне[-\\s]специальн${W}*\\s+или\\s+высш${W}*`, 'gi'),
  new RegExp(`с\\s+высш${W}*\\s+или\\s+средн${W}+`, 'gi'),
  new RegExp(`средн${W}+\\s+или\\s+высш${W}*`, 'gi'),
  new RegExp(`высш${W}*\\s+или\\s+же\\s+средн${W}+`, 'gi'),
  new RegExp(`высш${W}*\\s*,\\s*средн${W}+`, 'gi'),
];
const BENEFIT = [
  new RegExp(`возможност${W}*\\s+получени${W}*\\s+(?:средне[-\\s]специальн${W}*|высш${W}*)[^.]{0,70}образован`, 'gi'),
  new RegExp(`получен${W}*\\s+(?:средне[-\\s]специальн${W}*|высш${W}*)\\s+образован${W}*\\s+за\\s+счет`, 'gi'),
  new RegExp(`(?:высш${W}*|средне[-\\s]специальн${W}*)\\s+образован${W}*\\s+в\\s+процессе\\s+работы`, 'gi'),
  new RegExp(`получи${W}*\\s+высш${W}*\\s+образован`, 'gi'),
  new RegExp(`образован${W}*\\s+продолж${W}*\\s+получен`, 'gi'),
];
const PREFERRED = [
  new RegExp(`желательн${W}*\\s+(?:наличи${W}*\\s+)?высш${W}*\\s+образован`, 'gi'),
  new RegExp(`высш${W}*\\s+образован${W}*\\s*\\([^)]*желательн[^)]*\\)`, 'gi'),
  new RegExp(`высш${W}*\\s+образован${W}*\\s+желательн`, 'gi'),
  new RegExp(`будет\\s+преимуществом[^.]{0,60}высш`, 'gi'),
];

const PHRASES = [
  'Возможность получения средне-специального/высшего образования за счет предприятия; Программа адаптации',
  'Возможность получения среднего или высшего образования и карьерного роста до офицера',
  'Требования : высшее или среднее специальное образование в области строительства',
  'Высшее или среднее профессиональное образование (управленческое, экономическое, техническое)',
  'Требования к кандидату: высшее или среднее техническое образование, умение разбираться',
  'Требования: законченное средне-специальное или высшее образование.',
  'Требования: высшее или среднетехническое образование по сварочному производству',
  'Возможно трудоустройство Начинающих специалистов с средним и высшим профессиональным образованием.',
  'Наличие высшего образования (желательно, педагогического)',
  'Требования: • Высшее образование; средне-специальное образование;',
  'Наличие диплома о высшем образовании',
  'Требуется магистратура или специалитет',
];

for (const p of PHRASES) {
  let s = p;
  for (const r of OR_MEDIUM) s = s.replace(r, ' [ОР] ');
  for (const r of BENEFIT) s = s.replace(r, ' [ЛЬГОТА] ');
  for (const r of PREFERRED) s = s.replace(r, ' [ЖЕЛ] ');
  const tags = [];
  if (s.includes('[ОР]')) tags.push('ОР');
  if (s.includes('[ЛЬГОТА]')) tags.push('ЛЬГОТА');
  if (s.includes('[ЖЕЛ]')) tags.push('ЖЕЛ');
  console.log((tags.join('+') || '—').padEnd(14), p.slice(0, 78));
}
