// Модуль отбора вакансий по ТЗ: удалённо + без опыта + без высшего образования.
//
// Вынесен отдельно от сбора, потому что это и есть содержание требования, а всё
// остальное — транспорт. Проверять его нужно без сети, на текстах, иначе правку
// в фильтре нечем подтвердить, кроме как повторным обходом площадок.
//
// Три фильтра из ТЗ и почему каждый определяется именно так:
//
//   удалённо     поле площадки remoteWork либо формат работы, а НЕ слово
//                «удалённо» в тексте: вакансия может быть «удалённо, но после
//                испытательного срока в офисе», и это не то же самое, что
//                полностью удалённая
//   без опыта    нижняя граница. У него нет ни одного оплачиваемого рабочего
//                дня, поэтому любое «от N месяцев», любое «требуем опыт» и
//                любое «коммерческий опыт» — это отказ. Порог 12 месяцев
//                взят из hh-experience.js и используется тем же правилом, чтобы
//                два сборщика не решали одно и то же по-разному
//   без высшего   «высшее образование» в требованиях. Незаконченное СПО, которое
//                он заканчивает в 2027, пропускается — там нет слова «высшее»
//
// Отдельно: уровень вакансии. На Хабре метка Intern/Junior обязательна, потому
// что запрос «стажер» находит и Middle-вакансии; на hh метки достаточно в тексте.
const { reasonIn, MONTH_THRESHOLD } = require('./hh-experience.js');

// Приоритет стеков. Python первый — прямо по ТЗ. Дальше в порядке убывания
// пула по прошлым заходам: devops и qa дают больше всего вакансий.
const STACK_ORDER = ['python', 'devops', 'qa', 'backend', 'cpp', 'frontend', 'gamedev', 'devnull'];

// Правила стеков. Границы слов обязательны, и это не теория: без них «бот»
// находится внутри «разработчик», а он есть в каждой второй вакансии. Такой
// случай уже ловился дважды, в hh-target.js и hh-letter.js.
const STACK_RULES = [
  ['python', /(?<![а-яёa-z])(python|fastapi|flask|django|aiogram)(?![а-яёa-z])|парсер|парсинг|(?<![а-яёa-z])бот(?![а-яёa-z])|автоматизац/i],
  ['devops', /(?<![а-яёa-z])(devops|sre|docker|kubernetes|ansible)(?![а-яёa-z])|ci[ \/]?cd|инфраструктур|системный инженер|мониторинг/i],
  ['qa', /тестиров|тест-?инженер|автотест|(?<![а-яёa-z])(qa|sdet)(?![а-яёa-z])|quality assurance/i],
  ['backend', /(?<![а-яёa-z])(backend|api|rest)(?![а-яёa-z])|бэкенд|микросервис|интеграц|сервер/i],
  ['cpp', /c\+\+|qt|win32|gdi|opengl|vulkan|glfw|msvc|mingw|десктоп/i],
  ['frontend', /(?<![а-яёa-z])(frontend|javascript|react|vue|angular)(?![а-яёa-z])|фронтенд|верстальщик/i],
  ['gamedev', /(?<![а-яёa-z])(unity|unreal|godot|gamedev)(?![а-яёa-z])|(?<![а-яё])игр(?![а-яё])|движок/i],
];

// Заголовок без указания стека. Такая вакансия по ТЗ относится к приоритетной
// категории: «Стажёр-разработчик» — это python, а не «непонятно что».
const WEAK_GENERIC = /стаж[её]р-?разработчик|младший[ -]?разработчик|june?r[ -]?разработчик|junior[ -]?разработчик|разработчик-?стаж[её]р/i;

function stackOf(title, desc) {
  const t = (title || '').toLowerCase();
  const d = (desc || '').toLowerCase();
  let best = null;
  let bestScore = 0;
  for (const [name, re] of STACK_RULES) {
    const inTitle = (t.match(new RegExp(re.source, 'gi')) || []).length;
    const inDesc = (d.match(new RegExp(re.source, 'gi')) || []).length;
    // Заголовок весит вчетверо: в описании «Docker» мелькает у половины вакансий
    // как строка списка технологий, и без веса всё уезжало бы в devops.
    const score = inTitle * 4 + inDesc;
    if (score > bestScore) { bestScore = score; best = name; }
  }
  if (best) return best;
  // Ничего не нашлось: если заголовок обобщённый, отдаём python, иначе честно
  // отдаём devnull, чтобы такая вакансия не подменялась догадкой.
  if (WEAK_GENERIC.test(t)) return 'python';
  return 'devnull';
}

const RE_HIGHER_EDU = /высш[её][^.]{0,20}образован|незаконченн[ое][^.]{0,20}высш/i;
const RE_REMOTE_OK = /удаленн|удалённ|remote|работа из дома|на дому/i;
// Частичная удалёнка.
//
// Первая версия искала связку «удалённо → (после|в течение) → испыт», то есть
// опиралась на ПОРЯДОК слов, и поймала 2 из 6 настоящих формулировок:
//
//   ловила:    «гибридный формат…», «частично удаленная работа…»
//   пропускала: «удалённо, но в течение испытательного срока работа в офисе»
//               «удаленно, но первые 3 месяца в офисе»
//               «удалённая работа после прохождения испытательного срока»
//               «удаленно, периодически нужно приезжать в офис»
//
// Причина одна: в вакансиях слово «удалённо» стоит в конце фразы, а связка с
// ним шла слева направо. Теперь признаки независимы от порядка и от позиции:
//   * слово само по себе — «частично удалённо», «гибрид»;
//   * офис вообще упомянут рядом с удалёнкой — «…в офисе», «приезжать», «выходить»;
//   * испытательный срок рядом с местом работы — «испытательн», «адаптационн».
// Второй и третий признаки проверяются в пределах одного предложения: «в офисе
// в пяти годах от дома» не бывает, а «встречи в офисе раз в месяц» — бывает и
// означает частичную удалёнку.
const RE_HYBRID_WORD = /частично[ -]?удален|частично[ -]?удалённ|гибридн|hybrid|partially[ -]?remote/i;
// Предложение, в котором есть и офис, и удалёнка.
const RE_OFFICE = /в[ \t]+офис|офис[ \t]+(в|на|по|при)|приезжа|приезжат|на[ \t]+работ[уе][ \t]+в[ \t]+офис|в[ \t]+офисе|бывать[ \t]+в[ \t]+офис|в[ \t]+команд|meet[ \t]*office|on-?site/i;
const RE_TRIAL_PERIOD = /испытательн|адаптационн|пробнн[ыо]?[ \t]+период|probation/i;

// Наличие офиса в одном предложении с удалёнкой.
function partNamedIn(d) {
  const sentences = String(d || '').split(/(?<=[.!?;])\s+/);
  for (const s of sentences) {
    if (RE_REMOTE_OK.test(s) && RE_OFFICE.test(s)) return true;
    if (RE_TRIAL_PERIOD.test(s) && (RE_REMOTE_OK.test(s) || RE_OFFICE.test(s))) return true;
  }
  return RE_HYBRID_WORD.test(d);
}
// Явно полная удалёнка, перебивающая частичную.
const RE_REMOTE_FULL = /полностью[ -]?удален|удаленн[а-я]*[ ,.]*(?:формат|работа)?\s*(?:100\s*%|без огранич)/i;

/**
 * Решение по трём фильтрам ТЗ. Возвращает { ok, why, remote }.
 *
 * remote бывает 'full' | 'partial' | 'none'. partial не отсеивает — такая вакансия
 * подходит, просто сортировка опустит её ниже полностью удалённых, а в ТЗ сказано
 * «удалённо», а не «полностью удалённо».
 */
function screen(v) {
  const d = v.description || '';
  const remoteField = !!v.remoteField;

  // Частичная удалёнка, названная в тексте, отсеивается, а не просто помечается.
  //
  // Так было в первой версии: «гибридный формат: первые три месяца в офисе, далее
  // удалённо» считалось частичной удалёнкой и проходило. Это ровно та вакансия,
  // которая ему не подходит: ему нужно работать из Заречного, а в офис он не
  // поедет. Помечать «partial» можно только тогда, когда площадка сама пишет
  // удалённый формат, а текст не содержит слов про офис и испытательный срок.
  const partNamed = partNamedIn(d);
  let remote = 'none';
  if (RE_REMOTE_FULL.test(d)) remote = 'full';
  else if (partNamed) remote = 'partial';
  else if (remoteField) remote = 'full';
  else if (RE_REMOTE_OK.test(d)) remote = 'partial';

  if (remote === 'none') {
    return { ok: false, why: 'не удалённая', remote: remote };
  }
  if (remote === 'partial' && partNamed) {
    return { ok: false, why: 'частично удалённая: назван офис или испытательный срок', remote: remote };
  }

  // Уровень вакансии, если площадка его отдаёт. На Хабре метка Intern/Junior
  // обязательна: запрос «стажер» находит и Middle.
  if (v.level && !/intern|junior|стаж|student|трайон/i.test(String(v.level))) {
    return { ok: false, why: 'уровень не intern/junior: ' + v.level, remote: remote };
  }

  // Образование проверяется ДО опыта.
  //
  // Порядок определяет, что попадёт в отчёт: обе причины верны, но при обратном
  // порядке вакансию «требуется высшее образование + опыт от двух лет»
  // отклоняло по опыту, и по отчёту выглядело, что главное требование — опыт. В
  // отчёте должно быть видно, что мешает образование.
  if (RE_HIGHER_EDU.test(d)) {
    return { ok: false, why: 'требует высшего образования', remote: remote };
  }

  const why = reasonIn(d);
  if (why) return { ok: false, why: 'опыт: ' + why.rule, remote: remote };

  return { ok: true, remote: remote };
}

module.exports = { screen, stackOf, STACK_ORDER, MONTH_THRESHOLD };
