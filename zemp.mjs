// Тип работодателя — с тестом на реальные названия из выборки.
//
// ОШИБКА, КОТОРУЮ ПРИШЛОСЬ ИСПРАВИТЬ: аббревиатуры госучреждений
// (ФБУЗ, МУП, УК, ГБУ…) проверялись подстрокой, без границ слова.
// «ПрессБук» попадал в «госучреждение», потому что внутри слова «ПрессБук»\n// есть «ук». В JavaScript `\\b` с кириллицей не работает (это уже было
// записано в NOTES), поэтому границы заданы руками: буква — не буква.

const NB = '[^а-яёa-zA-Z0-9]';
// Аббревиатура как отдельное слово
function abbr(...list) {
  return new RegExp(`(^|${NB})(${list.join('|')})(${NB}|$)`, 'i');
}
// Аббревиатура в начале строки/слова, после может идти продолжение слова
// («СПСЧ», «ФГКУ Специальное…», «ФБУЗ МСЧ»)
function abbrAny(...list) {
  return new RegExp(list.join('|'), 'i');
}

const RE_GOV = [
  { re: abbr('ФБУЗ', 'ФГКУ', 'ФКУ', 'ФБУ', 'ФГБУ', 'ФГУП', 'ГБУ', 'МБУ', 'МАУ', 'МУП', 'КГУ', 'УК', 'ГКУ', 'МУ'), tag: 'госучреждение' },
  { re: abbr('ФМБА', 'МЧС', 'ФСБ', 'ФСО', 'МВД', 'ФСИН', 'ФКАО') , tag: 'силовые/госструктуры' },
  { re: /Росатом|НИПИГОРМАШ|Гринатом|ВУЭР|ЭСКМ|Рослесхоз|Ростехнадзор|Росреестр|Роспотребнадзор|Росгидромет/i, tag: 'госорган/госкорпорация' },
  { re: abbr('ФНС', 'ФСС', 'ФНФ', 'ПФР'), tag: 'госорган/госкорпорация' },
  { re: /больниц|поликлиник|медсанчасть|медчасть|стационар|диспансер|санатори|медцентр|ветлаборатор/i, tag: 'медучреждение' },
  { re: /школ|гимназ|лице[йя]|колледж|техникум|училищ|дошкольн|детск(ий|ая) сад|интернат|пансионат|литератур|музыкальн|хореограф/i, tag: 'образование' },
  { re: /администраци[яи] |мэрия|городск(ая|ой) округ|сельск(ая|ой) округ|поселени[ея] |волостн/i, tag: 'местная администрация' },
  { re: /центр (социальн|реабилитац)|соцзащит|комплексн(ый|ая) центр|центр помощи|приют|дом-интернат|социальн/i, tag: 'соцучреждение' },
  { re: /музей|библиотек|архив|театр|дворец культуры|парк развлечений|зоопарк|дом культуры/i, tag: 'учреждение культуры' },
  { re: /спортшкол|дюсш|сдюш|секци/i, tag: 'спортшкола' },
  { re: /водоканал|водоснабжен|теплосеть|горэнерго|жилищн(ые|ых) услуг|управляющ(ая|ие) компани|спорткомплекс/i, tag: 'МУП/коммунальное' },
  { re: /воинск(ая|ой) часть|часть \d+|полигон/i, tag: 'воинская часть' },
  { re: /казенн|казённ|бюджетн/i, tag: 'бюджетное учреждение' },
];
// Частные компании с госучастием — их тоже стоит отметить отдельно: там
// выше шанс взять студента, чем в мелком ИП.
//
// ВАЖНО: правила частных сетей проверяются ПЕРЕД правилами госструктур.
// Иначе «МАГНИТ, Розничная сеть» попадал в «госорган/госкорпорацию» по слову
// «Магнит», а «Сеть магазинов цифровой и бытовой техники DNS» — в
// «спортшкола» по слову «DNS». Обе ошибочно считались государственными.
const RE_BIG_PRIVATE = [
  /Пятёрочка|Перекресток|Магнит|Лента|Верный|Детский мир|Красное & Белое|Фаворит|Гала-центр|Сеть магазинов цифровой|DNS\b|Аптека|Плюс|Живика|МегаФон|МТС|Сбер\. Работа с клиентами|ANCOR|Оптима|Спортмастер|Ростелеком|К Телеком|Газпром|РЖД|Российские железные дороги|ВУЭР|ЭСКМ|Росатом|Гринатом|НИПИГОРМАШ/i,
];
// Госкомпании — их относят к «госструктурам», но в отчёте они отдельной строкой
const RE_GOV_COMPANY = /Ростелеком|К Телеком|Газпром|РЖД|Российские железные дороги|ВУЭР|ЭСКМ|Росатом|Гринатом|НИПИГОРМАШ/i;
// ИП и самозанятые — частные, без льгот.
const RE_IP = [abbr('ИП'), /индивидуальн(ый|ого) предпринимател/i];
const RE_SELF = [/самозанят/i, /фриланс/i];

export function employerType(name) {
  const n = String(name || '').trim();
  if (!n) return { tag: 'не указан', gov: false, priv: false, big: false };
  // Частные сети — ПЕРВЫМИ. Иначе «МАГНИТ, Розничная сеть» считался
  // госструктурой по слову «Магнит», а DNS — «спортшколой» по слову «DNS».
  if (RE_BIG_PRIVATE.some(r => r.test(n))) {
    if (RE_GOV_COMPANY.test(n)) return { tag: 'госкомпания', gov: true, priv: false, big: true };
    return { tag: 'крупная частная сеть', gov: false, priv: true, big: true };
  }
  for (const g of RE_GOV) if (g.re.test(n)) return { tag: g.tag, gov: true, priv: false, big: true };
  if (RE_IP.some(r => r.test(n))) return { tag: 'ИП', gov: false, priv: true, big: false };
  if (RE_SELF.some(r => r.test(n))) return { tag: 'самозанятый/фриланс', gov: false, priv: true, big: false };
  return { tag: 'частная компания', gov: false, priv: true, big: false };
}
