const { composeLetter, letterTags } = require('./hh-letter.js');
const cases = [
  ['Системный аналитик (стажер)', 'Нужно описывать требования, интеграции с внешними системами, документировать контракты.'],
  ['DevOps инженер (ученик)', 'Docker, linux, ci/cd, мониторинг, автоматизация выкатки.'],
  ['1С разработчик (ученик)', 'Разработка на 1С, запросы, интеграция с сайтом.'],
  ['Инженер по тестированию Java (стажер)', 'Автотесты selenium, регрессионное тестирование, покрытие.'],
  ['Младший инженер сервисной службы', 'Поддержка пользователей в чат-боте, интеграция с CRM.'],
  ['Что-то совсем незнакомое', 'Описание без ключевых слов вообще.']
];
for (const [t, d] of cases) {
  const l = composeLetter(t, d);
  console.log('=== ' + t + ' | ' + (letterTags(t, d).join(',') || 'нет совпадений') + ' | ' + l.length + ' зн.');
  console.log(l.split('\n').slice(0, 5).join('\n'));
  console.log('');
}
