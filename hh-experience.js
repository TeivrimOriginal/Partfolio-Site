function num(word) {
  if (word == null) return NaN;
  const w = String(word).toLowerCase().trim();
  if (/^\d+$/.test(w)) return parseInt(w, 10);
  if (Object.prototype.hasOwnProperty.call(MONTHS_WORD, w)) return MONTHS_WORD[w];
  if (Object.prototype.hasOwnProperty.call(YEARS_WORD, w)) return YEARS_WORD[w];
  return NaN;
}

function monthsOfYearToken(token) {
  const n = num(token);
  if (n !== n) return NaN;
  return n * 12;
}

// Минимальный опыт в месяцах, явно названный в тексте. 0 — не назван.
function monthsFloor(text) {
  let best = 0;
  let m;
  const n = (v) => { const x = v === undefined ? NaN : v; return x === x ? x : 0; };
  RE_YEARS.lastIndex = 0;
  while ((m = RE_YEARS.exec(text)) !== null) best = Math.max(best, monthsOfYearToken(m[1]));
  RE_MONTHS.lastIndex = 0;
  while ((m = RE_MONTHS.exec(text)) !== null) best = Math.max(best, n(num(m[1])));
  RE_MORE.lastIndex = 0;
  while ((m = RE_MORE.exec(text)) !== null) {
    // «Мы на рынке уже более 10 лет» и «компания работает более 30 лет» —
    // это возраст компании, а не требование опыта. Отличается тем, что после
    // этих чисел нет слова про опыт. Без проверки отсеивались вакансии
    // Эдди Сервис и Агротек, у которых ни одного реального порога не было.
    const after = text.slice(m.index, m.index + m[0].length + 60);
    if (!/опыт|работ|разработ|стаж|коммерческ/i.test(after)) continue;
    best = Math.max(best, /месяц/i.test(m[0]) ? n(parseInt(m[1], 10)) : n(parseInt(m[1], 10) * 12));
  }
  RE_RANGE.lastIndex = 0;
  while ((m = RE_RANGE.exec(text)) !== null) best = Math.max(best, parseInt(m[1], 10) * 12);
  RE_SINGLE.lastIndex = 0;
  while ((m = RE_SINGLE.exec(text)) !== null) best = Math.max(best, parseInt(m[1], 10) * 12);
  return best;
}

function around(t, index, size) {
  const w = size || 180;
  return t.slice(Math.max(0, index - 60), Math.min(t.length, index + w));
}

// Окно в пределах одного пункта списка: от предыдущей границы до следующей.
// Границы — точка с запятой, точка, запятая с пробелом и перевод строки.
//
// Отдельная функция, потому что фиксированное окно в 260 символов давало
// ложный отказ на «Аналитик данных»: чужое «не требуется опыт» из
// соседнего пункта попадало в окно и глушило настоящее требование.
function sentenceAround(t, index, size, matchedLength) {
  const cap = size || 200;
  const from = index + (matchedLength || 0);
  let start = index;
  while (start > 0 && index - start < 60) {
    const ch = t[start - 1];
    if (ch === ';' || ch === '\n' || (ch === '.' && !/[0-9]/.test(t[start - 2] || ''))) break;
    if (ch === ',' && t[start] === ' ') break;
    start--;
  }
  // Правая граница ищется от конца совпадения, а не от его начала.
  //
  // Иначе окно обрывается на той же точке, с которой началось совпадение:
  // в «Стажировка. Опыт работы не требуется» граница пункта — это ведущая
  // точка перед «Опыт», и правый обход на ней же останавливался. Окно
  // получалось равным «Стажировка», правило видело там ничего и отсевало
  // вакансию, где опыт прямо разрешено не иметь.
  let end = from;
  while (end < t.length && end - from < cap) {
    const ch = t[end];
    if (ch === ';' || ch === '\n') break;
    if (ch === '.' && !/[0-9]/.test(t[end + 1] || '')) break;
    end++;
  }
  return t.slice(start, end);
}

// Причина отказа по тексту описания. null — отказа нет.
function reasonIn(text) {
  const t = String(text == null ? '' : text);

  const edu = RE_EDU.exec(t);
  if (edu) return { rule: 'education', matched: edu[0], context: around(t, edu.index, edu[0].length) };

  // «уровень Middle» встречается и в требовании, и в перспективе роста:
  // «Знания на уровне middle-разработчика» против «вырасти до уровня Middle».
  // Различаем по глаголу в окне, а не по самим словам.
  const mid = RE_MIDDLE.exec(t);
  if (mid) {
    const win = around(t, mid.index, 240);
    if (!RE_MIDDLE_ALLOWED.test(win)) return { rule: 'level', matched: mid[0], context: win };
  }

  // «Коммерческий опыт»: ловится только рядом со словом про опыт или работу.
  // Отдельно пропускаем случаи, где требования нет вовсе: «без коммерческого
  // опыта» и «возможность получить коммерческий опыт».
  let cm;
  RE_COMMERCIAL.lastIndex = 0;
  while ((cm = RE_COMMERCIAL.exec(t)) !== null) {
    const before = t.slice(Math.max(0, cm.index - 40), cm.index);
    if (RE_COMMERCIAL_NEGATED.test(before)) continue;
    const win = around(t, cm.index, 240);
    if (RE_COMMERCIAL_ALLOWED.test(win)) continue;
    if (RE_ACCEPTS_PET.test(win)) continue;
    return { rule: 'commercial', matched: cm[0], context: win };
  }

  // Явное требование опыта без числового порога. Проверяется после вакансий с
  // числами, но до них: у вакансии «ожидаем опыт работы с Ansible, от двух лет»
  // важнее сообщить о числе — так понятнее, что именно не подходит.
  let es;
  RE_EXPERIENCE_STATED.lastIndex = 0;
  while ((es = RE_EXPERIENCE_STATED.exec(t)) !== null) {
    const before = t.slice(Math.max(0, es.index - 40), es.index);
    if (RE_EXPERIENCE_NEGATED.test(before)) continue;
    const win = around(t, es.index, 240);
    if (RE_EXPERIENCE_ALLOWED.test(win)) continue;
    // Та же проверка по названной технологии, что и в правиле ниже.
    //
    // Без неё «Требуется опыт работы с Docker» отсеивалось, хотя Docker у него
    // есть и он закрывает это требование: docker-compose на шесть сервисов с
    // healthcheck и depends_on. Триггер «требуется» ничего не говорит о том,
    // чего именно требуют.
    const tok = tokensIn(win);
    if (!tok.lacks.length) continue;
    return { rule: 'experience-stated', matched: es[0], context: win, lacks: tok.lacks };
  }

  // Требование опыта без триггерного слова: пункт списка начинается с «Опыт».
  //
  // Правило выше требует триггер («ожидаем», «требуем», «нужен») перед словом
  // «опыт». На настоящих вакансиях триггер есть не всегда — требование записано
  // самим пунком списка требований:
  //
  //   Опыт работы с оркестраторами (Airflow, Prefect и др.)
  //   Опыт разработки и поддержки etl-процессов
  //   Опыт интеграции с 1С
  //
  // Такая вакансия проходила отбор целиком: числа в ней нет, триггера нет, а
  // опыт требуется по трём позициям сразу, и у него его нет ни по одной.
  //
  // Мягчится тем же набором, что и предыдущее правило: «Будет плюсом опыт»
  // пропускается. Отдельно отсекается служебное «Опыт работы: Не указан» — на
  // агрегаторах такая подпись означает ровно обратное, и без этой оговорки
  // правило сработало бы почти на всей выдаче.
  let eb;
  RE_EXPERIENCE_BULLET.lastIndex = 0;
  while ((eb = RE_EXPERIENCE_BULLET.exec(t)) !== null) {
    const before = t.slice(Math.max(0, eb.index - 60), eb.index);
    if (RE_EXPERIENCE_NEGATED.test(before)) continue;
    // Окно считается от самого слова «Опыт», а не от начала совпадения.
    //
    // Совпадение начинается с границы пункта — точки или точки с запятой, —
    // и если искать границу окна оттуда, обход влево перескакивает эту точку
    // и захватывает хвост соседнего пункта. Так «Опыт создания небольших
    // сервисов или pet-проектов, которые можно показать» отсевалось из-за
    // Kafka, который стоял в предыдущем пункте про стек.
    const wordOffset = eb[0].toLowerCase().indexOf('опыт');
    const anchor = eb.index + (wordOffset > 0 ? wordOffset : 0);
    // Окно — только в пределах одного пункта, до точки с запятой или точки.
    //
    // Сначала было 260 символов, и это было неверно: в вакансии «Аналитик
    // данных» требование «Опыт работы с данными и автоматизацией» стоит в
    // начале, а через 200 символов в том же тексте идёт «не требуется опыт
    // полноценного backend-разработчика» — про другое требование. Окно
    // захватывало чужое предложение, правило молчало, и вакансия проходила
    // отбор, хотя опыт работы с данными там требуется прямо.
    const win = sentenceAround(t, anchor, 200, eb[0].length - (wordOffset > 0 ? wordOffset : 0));
    if (RE_EXPERIENCE_ALLOWED.test(win)) continue;
    // «pet-проекты подойдут» — прямое разрешение, и учебные проекты у него
    // есть. Для правила про коммерческий опыт это уже учтено отдельной строкой;
    // здесь та же оговорка нужна, потому что требование часто записано именно
    // так: «Опыт создания небольших сервисов или pet-проектов».
    if (RE_ACCEPTS_PET.test(win)) continue;
    // В пункте назван небольшой срок — это требование, которое он закрывает
    // учебными проектами, и порог 12 месяцев такие случаи пропускает.
    const sm = win.match(RE_SHORT_STATED);
    if (sm && Number(sm[1]) <= SHORT_MAX_MONTHS) continue;
    // Отсев только по названной технологии.
    //
    // Первая версия правила отсеивала любой пункт, начинающийся со слова «Опыт»,
    // и это убрало из отбора 26 из 127 вакансий, причём большинство — по его
    // собственному стеку: «Опыт разработки backend-приложений на FastAPI
    // (обязательно)», «опыт работы с Git, Docker», «Опыт работы с логами». Такой
    // отказ неправилен по сути: опыт у него есть, он просто не оплачиваемый, и
    // письмо про это прямо пишет.
    //
    // Отсеивает только то, чего у него нет и взять негде: Ansible, Kubernetes,
    // Airflow, RabbitMQ, Grafana, Prometheus, MS SQL, ClickHouse. Если технология
    // не названа или названа его — вакансия остаётся в отборе. Ошибиться в
    // сторону «оставить» дешевле: лишний отклик стоит одного, а снятая вакансия
    // стоит шанса.
    const tok = tokensIn(win);
    if (!tok.lacks.length) continue;
    return { rule: 'experience-bullet', matched: eb[0], context: win, lacks: tok.lacks };
  }

  const months = monthsFloor(t);
  if (months >= MONTH_THRESHOLD) {
    const first = new RegExp(RE_YEARS.source, 'i').exec(t) || new RegExp(RE_RANGE.source, 'i').exec(t) || new RegExp(RE_MONTHS.source, 'i').exec(t) || new RegExp(RE_MORE.source, 'i').exec(t);
    return {
      rule: 'floor',
      months: months,
      matched: first ? first[0] : months + ' мес',
      context: first ? around(t, first.index, first[0].length) : '',
    };
  }
  return null;
}

const MONTH_THRESHOLD = 12;

module.exports = {
  MONTH_THRESHOLD: MONTH_THRESHOLD,
  monthsFloor: monthsFloor,
  reasonIn: reasonIn,
  tooExperienced: function (text) {
    return reasonIn(text) !== null;
  },
};